"""Generate wire types from Rust JSON Schema; fail rather than silently erase unsupported shapes."""
from pathlib import Path
import json
root=Path(__file__).resolve().parents[1]
schema=json.loads((root/'docs/protocol.schema.json').read_text())
defs=schema['$defs']

def ts(s):
    if '$ref' in s:return s['$ref'].split('/')[-1]
    if 'const' in s:return json.dumps(s['const'])
    if 'enum' in s:return ' | '.join(json.dumps(x) for x in s['enum'])
    if 'oneOf' in s or 'anyOf' in s:return ' | '.join(ts(x) for x in s.get('oneOf',s.get('anyOf')))
    t=s.get('type')
    if isinstance(t,list):return ' | '.join(ts(dict(s,type=x)) for x in t)
    if t=='object':return '{ '+ '; '.join(json.dumps(k)+('' if k in s.get('required',[]) else '?')+': '+ts(v) for k,v in s.get('properties',{}).items())+' }'
    if t=='array':
        if 'prefixItems' in s:return '['+', '.join(ts(x) for x in s['prefixItems'])+']'
        if s.get('minItems')==s.get('maxItems') and s.get('maxItems',100)<=32:return '['+', '.join([ts(s['items'])]*s['maxItems'])+']'
        return '('+ts(s['items'])+')[]'
    if t in ['number','integer']:return 'number'
    if t in ['boolean','string','null']:return t
    raise ValueError(s)

py_lines=['# Generated by scripts/generate_clients.py. Do not edit.','from typing import Literal, TypedDict, Required, NotRequired, Union, TypeAlias']
used_names=set(defs)
def object_definition(name,s):
    fields=[]
    for key,value in s.get('properties',{}).items():
        field_type=py(value,name+''.join(x.title() for x in key.split('_')))
        wrapper='Required' if key in s.get('required',[]) else 'NotRequired'
        fields.append(repr(key)+': '+wrapper+'['+field_type+']')
    py_lines.append(name+' = TypedDict('+repr(name)+', {'+', '.join(fields)+'})')
def py(s,hint):
    if '$ref' in s:return repr(s['$ref'].split('/')[-1])
    if 'const' in s:return 'Literal['+repr(s['const'])+']'
    if 'enum' in s:return 'Literal['+', '.join(repr(x) for x in s['enum'])+']'
    if 'oneOf' in s or 'anyOf' in s:
        variants=s.get('oneOf',s.get('anyOf'))
        return 'Union['+', '.join(py(x,hint+'Variant'+str(i)) for i,x in enumerate(variants))+']'
    t=s.get('type')
    if isinstance(t,list):return 'Union['+', '.join(py(dict(s,type=x),hint+str(i)) for i,x in enumerate(t))+']'
    if t=='object':
        name=hint
        while name in used_names:name+='Nested'
        used_names.add(name)
        object_definition(name,s)
        return repr(name)
    if t=='array':return 'list['+('Union['+', '.join(py(x,hint+'Item'+str(i)) for i,x in enumerate(s['prefixItems']))+']' if 'prefixItems' in s else py(s['items'],hint+'Item'))+']'
    if t in ['number','integer']:return 'float' if t=='number' else 'int'
    if t in ['boolean','string','null']:return {'boolean':'bool','string':'str','null':'None'}[t]
    raise ValueError(s)

ts_lines=['// Generated by scripts/generate_clients.py. Do not edit.']
for name,s in defs.items():
    ts_lines.append('export type '+name+' = '+ts(s)+';')
    if s.get('type')=='object':object_definition(name,s)
    else:py_lines.append(name+': TypeAlias = '+py(s,name))
(root/'clients/typescript/src/types.ts').write_text('\n'.join(ts_lines)+'\n')
(root/'clients/python/settlers_client/types.py').write_text('\n'.join(py_lines)+'\n')
